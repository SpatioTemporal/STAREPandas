def test_path_structure_analysis(expected_paths):
    """Analyze the hierarchical path structure."""
    print("\n=== Path Structure Analysis ===")
    
    if not expected_paths:
        print("No paths to analyze")
        return
    
    print("Hierarchical path analysis:")
    
    for group_id, hierarchical_path, full_path, row_count in expected_paths:
        components = hierarchical_path.split('/')
        levels = len(components) - 1  # Subtract 1 for dataset name
        
        print(f"\nGroup {group_id}:")
        print(f"  - Path: {hierarchical_path}")
        print(f"  - Hierarchy levels: {levels}")
        print(f"  - Path components: {components}")
        print(f"  - Rows: {row_count}")
        
        # Parse the path back to verify
        from starepandas.io.granules import parse_zarr_path
        try:
            parsed_sid, parsed_dataset = parse_zarr_path(hierarchical_path)
            print(f"  - Parsed SID: {parsed_sid}")
            print(f"  - Parsed dataset: {parsed_dataset}")
            
            # Check level consistency
            original_levels = (group_id & 0x1F) + 1
            parsed_levels = (parsed_sid & 0x1F) + 1
            consistent = original_levels == parsed_levels
            print(f"  - Level consistency: {'✓' if consistent else '✗'}")
            
        except Exception as e:
            print(f"  - Parse error: {e}")
    
    # Analyze spatial organization
    print(f"\nSpatial organization benefits:")
    
    # Group by common prefixes
    prefix_groups = {}
    for group_id, hierarchical_path, full_path, row_count in expected_paths:
        components = hierarchical_path.split('/')[:-1]  # Remove dataset
        if len(components) >= 2:
            prefix = '/'.join(components[:2])  # First 2 levels
            if prefix not in prefix_groups:
                prefix_groups[prefix] = []
            prefix_groups[prefix].append((group_id, row_count))
    
    for prefix, groups in prefix_groups.items():
        total_rows = sum(row_count for _, row_count in groups)
        print(f"  - Region '{prefix}': {len(groups)} groups, {total_rows} total rows")


